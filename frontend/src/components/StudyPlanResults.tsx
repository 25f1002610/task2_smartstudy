import React, { useState } from 'react';
import { StudyPlanResponse, DayPlan } from '../types';
import { QualityBadge } from './QualityBadge';
import { TopicBreakdown } from './TopicBreakdown';
import { DayCard } from './DayCard';
import { 
  Calendar, 
  Clock, 
  Target, 
  BookOpen, 
  FileText, 
  LayoutGrid, 
  Copy, 
  Check, 
  Sparkles,
  ArrowLeft,
  Share2
} from 'lucide-react';

interface StudyPlanResultsProps {
  response: StudyPlanResponse;
  onReset: () => void;
}

export const StudyPlanResults: React.FC<StudyPlanResultsProps> = ({ response, onReset }) => {
  const [viewMode, setViewMode] = useState<'cards' | 'markdown'>('cards');
  const [copied, setCopied] = useState(false);

  const { structured_data, summary_metrics, final_markdown } = response;
  const draft = structured_data?.draft_plan;
  const dayPlans: DayPlan[] = draft?.day_by_day_plan || [];

  const handleCopyMarkdown = () => {
    navigator.clipboard.writeText(final_markdown);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="space-y-8 animate-in fade-in duration-300">
      {/* Top Bar with Metrics */}
      <div className="bg-white rounded-3xl p-8 border border-stone-200/90 shadow-sm space-y-6">
        <div className="flex flex-col md:flex-row md:items-center justify-between gap-4 pb-6 border-b border-stone-100">
          <div>
            <div className="flex items-center gap-2 mb-1">
              <span className="text-xs font-semibold uppercase tracking-wider text-amber-700 bg-amber-50 px-2.5 py-1 rounded-full border border-amber-200/80">
                {summary_metrics.current_level} Level
              </span>
              <span className="text-xs text-stone-400 font-medium">·</span>
              <span className="text-xs font-semibold text-emerald-700 bg-emerald-50 px-2.5 py-1 rounded-full border border-emerald-200/80">
                ADK Multi-Agent Verified
              </span>
            </div>
            <h1 className="text-3xl font-extrabold text-stone-900 tracking-tight font-serif-editorial">
              {summary_metrics.subject} Study Blueprint
            </h1>
            <p className="text-xs text-stone-500 mt-1 max-w-2xl leading-relaxed">
              {draft?.plan_overview ||
                `Personalized ${summary_metrics.exam_in_days}-day preparation schedule generated by coordinated Google ADK agents.`}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setViewMode(viewMode === 'cards' ? 'markdown' : 'cards')}
              className="px-3.5 py-2 rounded-xl border border-stone-200 bg-stone-50 hover:bg-white text-xs font-semibold text-stone-700 flex items-center gap-1.5 transition-colors"
            >
              {viewMode === 'cards' ? (
                <>
                  <FileText className="w-3.5 h-3.5 text-stone-500" />
                  View Markdown
                </>
              ) : (
                <>
                  <LayoutGrid className="w-3.5 h-3.5 text-stone-500" />
                  View Day Cards
                </>
              )}
            </button>

            <button
              onClick={handleCopyMarkdown}
              className="px-3.5 py-2 rounded-xl border border-stone-200 bg-stone-50 hover:bg-white text-xs font-semibold text-stone-700 flex items-center gap-1.5 transition-colors"
            >
              {copied ? (
                <>
                  <Check className="w-3.5 h-3.5 text-emerald-600" />
                  Copied!
                </>
              ) : (
                <>
                  <Copy className="w-3.5 h-3.5 text-stone-500" />
                  Copy Plan
                </>
              )}
            </button>

            <button
              onClick={onReset}
              className="px-4 py-2 rounded-xl bg-stone-900 text-white hover:bg-stone-800 text-xs font-semibold flex items-center gap-1.5 transition-colors shadow-sm"
            >
              <ArrowLeft className="w-3.5 h-3.5" />
              Adjust Inputs
            </button>
          </div>
        </div>

        {/* 4 Key Stat Badges */}
        <div className="grid grid-cols-2 md:grid-cols-4 gap-4">
          <div className="p-4 rounded-2xl bg-stone-50/70 border border-stone-200/80 space-y-1">
            <span className="text-[11px] font-semibold text-stone-500 uppercase tracking-wider flex items-center gap-1.5">
              <Calendar className="w-3.5 h-3.5 text-amber-600" />
              Duration
            </span>
            <div className="text-xl font-bold font-mono text-stone-900">
              {summary_metrics.exam_in_days} Days
            </div>
            <p className="text-[10px] text-stone-400">Total preparation span</p>
          </div>

          <div className="p-4 rounded-2xl bg-stone-50/70 border border-stone-200/80 space-y-1">
            <span className="text-[11px] font-semibold text-stone-500 uppercase tracking-wider flex items-center gap-1.5">
              <Clock className="w-3.5 h-3.5 text-amber-600" />
              Daily Limit
            </span>
            <div className="text-xl font-bold font-mono text-stone-900">
              {summary_metrics.hours_per_day}h / day
            </div>
            <p className="text-[10px] text-stone-400">Strictly enforced ceiling</p>
          </div>

          <div className="p-4 rounded-2xl bg-stone-50/70 border border-stone-200/80 space-y-1">
            <span className="text-[11px] font-semibold text-stone-500 uppercase tracking-wider flex items-center gap-1.5">
              <BookOpen className="w-3.5 h-3.5 text-amber-600" />
              Total Hours
            </span>
            <div className="text-xl font-bold font-mono text-stone-900">
              {summary_metrics.total_study_hours} Hours
            </div>
            <p className="text-[10px] text-stone-400">Theory + Coding Drills</p>
          </div>

          <div className="p-4 rounded-2xl bg-stone-50/70 border border-stone-200/80 space-y-1">
            <span className="text-[11px] font-semibold text-stone-500 uppercase tracking-wider flex items-center gap-1.5">
              <Target className="w-3.5 h-3.5 text-amber-600" />
              Practice Target
            </span>
            <div className="text-xl font-bold font-mono text-stone-900">
              {draft?.total_practice_problems || '30+'} Problems
            </div>
            <p className="text-[10px] text-stone-400">Across all 5 topics</p>
          </div>
        </div>
      </div>

      {/* Quality Review Audit Panel */}
      <QualityBadge
        reviewFeedback={structured_data?.review_feedback}
        status={summary_metrics.review_status}
      />

      {/* Topic Analysis Grid */}
      {structured_data?.topic_analysis?.topics && (
        <TopicBreakdown
          topics={structured_data.topic_analysis.topics}
          practiceItems={structured_data?.practice_plan?.topic_practice}
        />
      )}

      {/* Main View: Day Cards or Markdown */}
      {viewMode === 'cards' ? (
        <div className="space-y-4">
          <div className="flex items-center justify-between px-1">
            <h3 className="text-base font-bold text-stone-900 flex items-center gap-2">
              <Calendar className="w-4 h-4 text-amber-600" />
              10-Day Daily Study Timeline
            </h3>
            <span className="text-xs text-stone-500">
              Showing {dayPlans.length} detailed daily schedules
            </span>
          </div>

          <div className="space-y-3">
            {dayPlans.map((dayPlan) => (
              <DayCard
                key={dayPlan.day}
                dayPlan={dayPlan}
                maxDailyHours={summary_metrics.hours_per_day}
              />
            ))}
          </div>
        </div>
      ) : (
        <div className="bg-white rounded-3xl p-8 border border-stone-200/90 shadow-sm space-y-4">
          <div className="flex items-center justify-between pb-3 border-b border-stone-100">
            <h3 className="text-sm font-bold text-stone-900 flex items-center gap-2">
              <FileText className="w-4 h-4 text-amber-600" />
              Full Markdown Schedule Document
            </h3>
            <button
              onClick={handleCopyMarkdown}
              className="text-xs text-amber-700 hover:text-amber-800 font-semibold flex items-center gap-1"
            >
              {copied ? 'Copied!' : 'Copy to Clipboard'}
            </button>
          </div>
          <div className="p-5 rounded-2xl bg-stone-50/70 border border-stone-200 font-mono text-xs text-stone-800 whitespace-pre-wrap leading-relaxed overflow-x-auto max-h-[600px] overflow-y-auto">
            {final_markdown}
          </div>
        </div>
      )}
    </div>
  );
};
